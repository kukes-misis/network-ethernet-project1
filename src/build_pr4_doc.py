    doc_out.styles.addElement(s_h2)

    s_tbl_title = style.Style(name='TableTitle', family='paragraph')
    s_tbl_title.addElement(style.ParagraphProperties(textalign='left', textindent='1.25cm', lineheight='115%', margintop='0.25cm', marginbottom='0.1cm'))
    s_tbl_title.addElement(style.TextProperties(fontname='Times New Roman', fontsize='12pt'))
    doc_out.styles.addElement(s_tbl_title)

    s_fig_caption = style.Style(name='FigCaption', family='paragraph')
    s_fig_caption.addElement(style.ParagraphProperties(textalign='center', textindent='0cm', lineheight='115%', margintop='0.1cm', marginbottom='0.3cm'))
    s_fig_caption.addElement(style.TextProperties(fontname='Times New Roman', fontsize='11.5pt'))
    doc_out.styles.addElement(s_fig_caption)

    s_tbl_cell = style.Style(name='TableCellStyle', family='paragraph')
    s_tbl_cell.addElement(style.ParagraphProperties(textalign='center', textindent='0cm', lineheight='105%', marginbottom='0.05cm', margintop='0.05cm'))
    s_tbl_cell.addElement(style.TextProperties(fontname='Times New Roman', fontsize='9.0pt'))
    doc_out.styles.addElement(s_tbl_cell)

    s_tbl_cell_bold = style.Style(name='TableCellStyleBold', family='paragraph')
    s_tbl_cell_bold.addElement(style.ParagraphProperties(textalign='center', textindent='0cm', lineheight='105%', marginbottom='0.05cm', margintop='0.05cm'))
    s_tbl_cell_bold.addElement(style.TextProperties(fontname='Times New Roman', fontsize='9.0pt', fontweight='bold'))
    doc_out.styles.addElement(s_tbl_cell_bold)

    s_tbl_left = style.Style(name='TableCellLeft', family='paragraph')
    s_tbl_left.addElement(style.ParagraphProperties(textalign='left', textindent='0cm', lineheight='105%', marginbottom='0.05cm', margintop='0.05cm'))
    s_tbl_left.addElement(style.TextProperties(fontname='Times New Roman', fontsize='9.0pt'))
    doc_out.styles.addElement(s_tbl_left)

    tc_style = style.Style(name='TableColumnStyleBorder', family='table-cell')
    tc_style.addElement(style.TableCellProperties(border='0.05pt solid #000000', padding='0.1cm'))
    doc_out.styles.addElement(tc_style)

    img_map = {
        'Рисунок 1': ('fig4_ethernet_frame.png', '16.0cm', '6.4cm'),
        'Рисунок 2': ('fig1_architecture.png', '16.0cm', '12.0cm'),
        'Рисунок 3': ('fig5_topology.png', '16.0cm', '8.2cm'),
        'Рисунок 4': ('fig2_benchmark_latency.png', '16.0cm', '6.8cm'),
        'Рисунок 5': ('fig3_database_performance.png', '16.0cm', '6.8cm')
    }

    for elem in doc_in.element.body:
        tag = elem.tag.split('}')[-1]
        if tag == 'p':
            p_obj = docx.text.paragraph.Paragraph(elem, doc_in)
            txt = p_obj.text.strip()
            if not txt:
                continue
            
            is_fig_cap = False
            for fig_key, (img_fname, w_cm, h_cm) in img_map.items():
                if txt.startswith(fig_key):
                    is_fig_cap = True
                    img_path = os.path.join(img_dir, img_fname)
                    if os.path.exists(img_path):
                        photo_href = doc_out.addPicture(img_path)
                        p_img = text.P(stylename=s_center)
                        df = draw.Frame(width=w_cm, height=h_cm, zindex=0, anchortype='as-char')
                        df.addElement(draw.Image(href=photo_href))
                        p_img.addElement(df)
                        doc_out.text.addElement(p_img)
                    p_odf = text.P(stylename=s_fig_caption, text=txt)
                    doc_out.text.addElement(p_odf)
                    break
            if is_fig_cap:
                continue

            if txt.startswith(('1 ', '2 ', '3 ', '4 ', '5 ', '6 ', '7 ', '8 ', 'СПИСОК')):
                p_odf = text.P(stylename=s_h1, text=txt)
                doc_out.text.addElement(p_odf)
            elif any(txt.startswith(f"{i}.") for i in range(1, 9)):
                p_odf = text.P(stylename=s_h2, text=txt)
                doc_out.text.addElement(p_odf)
            elif txt.startswith('Таблица'):
                p_odf = text.P(stylename=s_tbl_title, text=txt)
                doc_out.text.addElement(p_odf)
            elif any(txt.startswith(w) for w in ['МИНИСТЕРСТВО', 'ИНСТИТУТ', 'Кафедра', 'ОТЧЕТ', 'по курсу', 'Выполнил', 'Проверил', 'Москва']):
                p_odf = text.P(stylename=s_title_bold if ('МИНИСТЕРСТВО' in txt or 'ОТЧЕТ' in txt or 'МИСИС' in txt) else s_center, text=txt)
                doc_out.text.addElement(p_odf)
            else:
                p_odf = text.P(stylename=s_body, text=txt)
                doc_out.text.addElement(p_odf)
                
        elif tag == 'tbl':
            tbl_obj = docx.table.Table(elem, doc_in)
            if len(tbl_obj.rows) == 2 and len(tbl_obj.columns) == 2 and ('Выполнил' in tbl_obj.rows[0].cells[1].text or 'Выполнили' in tbl_obj.rows[0].cells[1].text):
                p_auth = text.P(stylename=s_body, text='Выполнили: студенты гр. БИВТ-26-6-9:\n1. Ерепов К. М. — Старший группы, докладчик\n2. Кашин С. К. — Дизайнер, работа с доской\n3. Якушевский И. И. — Составитель теста (тестер)\n4. Утяцкий В. С. — Программист\n5. Горбунов К. В. — Коммуникатор (коммуникация)\n\nПроверил: к.т.н., с.н.с. Микитенко И. И.')
                doc_out.text.addElement(p_auth)
                continue
                
            t_odf = table.Table()
            for r_idx, row in enumerate(tbl_obj.rows):
                tr_odf = table.TableRow()
                for c_idx, cell in enumerate(row.cells):
                    tc_odf = table.TableCell(stylename=tc_style)
                    c_txt = cell.text.strip()
                    st = s_tbl_cell_bold if r_idx == 0 else (s_tbl_left if (c_idx in (1, 2, 4, 5) or len(c_txt) > 20) else s_tbl_cell)
                    p_c = text.P(stylename=st, text=c_txt)
                    tc_odf.addElement(p_c)
                    tr_odf.addElement(tc_odf)
                t_odf.addElement(tr_odf)
            doc_out.text.addElement(t_odf)

    doc_out.save(odt_path)
    print(f"Successfully exported ODT with images via odfpy: {odt_path}")

