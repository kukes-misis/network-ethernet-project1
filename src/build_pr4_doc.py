def export_docx_to_odt_odfpy(docx_path, odt_path, img_dir):
    try:
        import odf.opendocument
        from odf import style, text, table, draw
        
        doc_in = docx.Document(docx_path)
        doc_out = odf.opendocument.OpenDocumentText()
        
        s_body = style.Style(name='BodyTextCustom', family='paragraph')
        s_body.addElement(style.ParagraphProperties(textalign='justify', textindent='1.25cm', lineheight='115%', marginbottom='0.1cm', margintop='0.05cm'))
        s_body.addElement(style.TextProperties(fontname='Times New Roman', fontsize='12pt'))
        doc_out.styles.addElement(s_body)

        s_h1 = style.Style(name='Heading1Custom', family='paragraph')
        s_h1.addElement(style.ParagraphProperties(textalign='center', textindent='0cm', lineheight='115%', margintop='0.4cm', marginbottom='0.2cm'))
        s_h1.addElement(style.TextProperties(fontname='Times New Roman', fontsize='14pt', fontweight='bold'))
        doc_out.styles.addElement(s_h1)

        tc_style = style.Style(name='TableColumnStyleBorder', family='table-cell')
        tc_style.addElement(style.TableCellProperties(border='0.05pt solid #000000', padding='0.1cm'))
        doc_out.styles.addElement(tc_style)

        for elem in doc_in.element.body:
            tag = elem.tag.split('}')[-1]
            if tag == 'p':
                p_obj = docx.text.paragraph.Paragraph(elem, doc_in)
                txt = p_obj.text.strip()
                if not txt:
                    continue
                if txt.startswith(('ВВЕДЕНИЕ', 'СОДЕРЖАНИЕ', 'СПИСОК', 'ПРИЛОЖЕНИЕ')) or re.match(r'^\d+\s+[А-ЯA-Z]', txt):
                    p_odf = text.P(stylename=s_h1, text=txt)
                    doc_out.text.addElement(p_odf)
                else:
                    p_odf = text.P(stylename=s_body, text=txt)
                    doc_out.text.addElement(p_odf)
            elif tag == 'tbl':
                tbl_obj = docx.table.Table(elem, doc_in)
                t_odf = table.Table()
                for row in tbl_obj.rows:
                    tr_odf = table.TableRow()
                    for cell in row.cells:
                        tc_odf = table.TableCell(stylename=tc_style)
                        p_c = text.P(text=cell.text.strip())
                        tc_odf.addElement(p_c)
                        tr_odf.addElement(tc_odf)
                    t_odf.addElement(tr_odf)
                doc_out.text.addElement(t_odf)

        doc_out.save(odt_path)
        print(f"Generated ODT: {odt_path}")
    except Exception as e:
        print(f"ODT export note: {e}")


