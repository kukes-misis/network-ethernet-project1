def export_docx_to_pdf_pages(docx_path, pdf_path):
    applescript = f'''
    tell application "Pages"
        activate
        set doc to open POSIX file "{docx_path}"
        export doc to POSIX file "{pdf_path}" as PDF
        close doc saving no
    end tell
    '''
    try:
        res = subprocess.run(["osascript", "-e", applescript], capture_output=True, text=True, check=True)
        print(f"Successfully exported PDF via Apple Pages: {pdf_path}")
        return True
    except subprocess.CalledProcessError as e:
        print(f"Error exporting PDF via Apple Pages: {e.stderr}")
        return False

