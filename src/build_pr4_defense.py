def add_clean_paragraph_runs(p, text):
    pattern = re.compile(r'(\*\*[^*]+\*\*|\*[^*]+\*|`[^`]+`|\[[^\]]+\]\([^)]+\))')
    tokens = pattern.split(text)

    for token in tokens:
        if not token:
            continue
        if token.startswith('**') and token.endswith('**') and len(token) >= 4:
            r = p.add_run(token[2:-2])
            r.bold = True
        elif token.startswith('*') and token.endswith('*') and len(token) >= 2:
            r = p.add_run(token[1:-1])
            r.italic = True
        elif token.startswith('`') and token.endswith('`') and len(token) >= 2:
            r = p.add_run(token[1:-1])
            r.font.name = 'Consolas'
            r.font.size = Pt(10)
            r.font.color.rgb = RGBColor(0x80, 0x10, 0x20)
        elif token.startswith('[') and ']' in token and '(' in token and token.endswith(')'):
            m = re.match(r'\[([^\]]+)\]\(([^)]+)\)', token)
            if m:
                link_text = m.group(1)
                r = p.add_run(link_text)
                r.font.color.rgb = RGBColor(0x00, 0x56, 0xb3)
                r.underline = True
            else:
                p.add_run(token)
        else:
            p.add_run(token)


