def generate_defense_files():
    # 1. Запись Markdown
    with open(OUT_MD, 'w', encoding='utf-8') as f:
        f.write(DEFENSE_CONTENT)
    print(f"Generated MD: {OUT_MD}")

    # 2. Генерация DOCX
    doc = docx.Document()
    for sec in doc.sections:
        sec.top_margin = Cm(2.0)
        sec.bottom_margin = Cm(2.0)
        sec.left_margin = Cm(2.5)
        sec.right_margin = Cm(1.5)

    style_normal = doc.styles['Normal']
    style_normal.font.name = 'Times New Roman'
    style_normal.font.size = Pt(11)

    for line in DEFENSE_CONTENT.split('\n'):
        line_s = line.strip()
        if not line_s:
            continue
        p = doc.add_paragraph()
        p.paragraph_format.line_spacing = 1.15
        p.paragraph_format.space_after = Pt(2)
        
        if line_s.startswith('# '):
            p.paragraph_format.space_before = Pt(8)
            p.paragraph_format.space_after = Pt(4)
            r = p.add_run(line_s[2:])
            r.bold = True
            r.font.size = Pt(14)
            r.font.color.rgb = RGBColor(0x1a, 0x2a, 0x3a)
        elif line_s.startswith('## '):
            p.paragraph_format.space_before = Pt(6)
            p.paragraph_format.space_after = Pt(3)
            r = p.add_run(line_s[3:])
            r.bold = True
            r.font.size = Pt(12.5)
            r.font.color.rgb = RGBColor(0x00, 0x56, 0xb3)
        elif line_s.startswith('### '):
            p.paragraph_format.space_before = Pt(4)
            p.paragraph_format.space_after = Pt(2)
            r = p.add_run(line_s[4:])
            r.bold = True
            r.font.size = Pt(11.5)
        elif line_s.startswith('> '):
            p.paragraph_format.left_indent = Cm(0.8)
            r = p.add_run(line_s[2:])
            r.italic = True
            r.font.color.rgb = RGBColor(0x2c, 0x3e, 0x50)
        elif line_s.startswith('---'):
            continue
        else:
            p.paragraph_format.left_indent = Cm(0.4) if line_s.startswith(('- ', '* ')) else Cm(0)
            r = p.add_run(line_s)

    doc.save(OUT_DOCX)
    print(f"Generated DOCX: {OUT_DOCX}")

    # 3. Генерация PDF через Apple Pages
    applescript = f'''
    tell application "Pages"
        activate
        set doc to open POSIX file "{OUT_DOCX}"
        export doc to POSIX file "{OUT_PDF}" as PDF
        close doc saving no
    end tell
    '''
    try:
        subprocess.run(["osascript", "-e", applescript], check=True, capture_output=True)
        print(f"Generated PDF via Pages: {OUT_PDF}")
    except Exception as e:
        print(f"Pages conversion error: {e}")

if __name__ == "__main__":
    generate_defense_files()
