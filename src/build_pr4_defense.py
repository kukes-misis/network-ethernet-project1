def md_to_html(md_text):
    """Преобразует Markdown плана защиты в чистый стилизованный HTML для экспорта в PDF."""
    html_lines = []
    in_quote = False
    in_list = False

    lines = md_text.strip().split('\n')
    for line in lines:
        line_s = line.strip()
        if not line_s:
            if in_quote:
                html_lines.append('</blockquote>')
                in_quote = False
            if in_list:
                html_lines.append('</ul>')
                in_list = False
            continue

        if line_s.startswith('---'):
            if in_quote:
                html_lines.append('</blockquote>')
                in_quote = False
            if in_list:
                html_lines.append('</ul>')
                in_list = False
            html_lines.append('<hr/>')
            continue

        if line_s.startswith('# '):
            html_lines.append(f'<h1>{line_s[2:].strip()}</h1>')
            continue
        if line_s.startswith('## '):
            html_lines.append(f'<h2>{line_s[3:].strip()}</h2>')
            continue
        if line_s.startswith('### '):
            html_lines.append(f'<h3>{line_s[4:].strip()}</h3>')
            continue

        if line_s.startswith('> '):
            if not in_quote:
                html_lines.append('<blockquote>')
                in_quote = True
            text_inside = line_s[2:].strip()
            # Преобразуем инлайн разметку
            text_inside = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', text_inside)
            text_inside = re.sub(r'\*([^*]+)\*', r'<em>\1</em>', text_inside)
            html_lines.append(f'<p>{text_inside}</p>')
            continue
        else:
            if in_quote:
                html_lines.append('</blockquote>')
                in_quote = False

        if line_s.startswith(('- ', '* ')):
            if not in_list:
                html_lines.append('<ul>')
                in_list = True
            text_inside = line_s[2:].strip()
            text_inside = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', text_inside)
            text_inside = re.sub(r'\*([^*]+)\*', r'<em>\1</em>', text_inside)
            text_inside = re.sub(r'`([^`]+)`', r'<code>\1</code>', text_inside)
            html_lines.append(f'<li>{text_inside}</li>')
            continue
        else:
            if in_list:
                html_lines.append('</ul>')
                in_list = False

        # Обычный абзац
        text_p = line_s
        text_p = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', text_p)
        text_p = re.sub(r'\*([^*]+)\*', r'<em>\1</em>', text_p)
        text_p = re.sub(r'`([^`]+)`', r'<code>\1</code>', text_p)
        text_p = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', r'<a href="\2">\1</a>', text_p)
        html_lines.append(f'<p>{text_p}</p>')

    if in_quote:
        html_lines.append('</blockquote>')
    if in_list:
        html_lines.append('</ul>')

    body_html = '\n'.join(html_lines)

