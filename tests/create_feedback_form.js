/**
 * Google Apps Script для автоматического создания Google Формы:
 * «Форма экспертной оценки и взаимного рецензирования (Peer-Review) Проекта № 1»
 * Лабораторная работа № 4: «Современные сети и системы: исследование сетевого оборудования и понятий»
 * Задание группы № 1: «Проводная сеть Ethernet, режимы работы и стандарты сетевых устройств»
 * Курс: «Вычислительные машины, сети и системы» (НИТУ МИСИС, кафедра ИКТ)
 * Преподаватель: к.т.н., с.н.с. Микитенко И. И.
 * 
 * Команда проекта (гр. БИВТ-26-6-9, 5 человек):
 * 1. Ерепов Кирилл Максимович (Старший группы, ведущий докладчик)
 * 2. Кашин Степан Кириллович (Дизайнер, виртуальная интерактивная доска)
 * 3. Утяцкий Владислав Сергеевич (Программист, моделирование сетевой инфраструктуры)
 * 4. Якушевский Игорь Игоревич (Тестер, фонд оценочных средств)
 * 5. Горбунов Константин Васильевич (Коммуникатор, координатор регламента)
 * 
 * ИНСТРУКЦИЯ (создание за 1 минуту):
 * 1. Перейдите по ссылке: https://script.new
 * 2. Вставьте весь этот код и нажмите «Выполнить» (Run / Play ▶).
 * 3. В журнале выполнения появятся готовые ссылки на форму и прохождение!
 */

function createProjectReviewForm() {
  const form = FormApp.create('Экспертная оценка Проекта № 1: Проводная сеть Ethernet и сетевые устройства');
  
  form.setDescription(
    'Форма взаимного рецензирования (Peer Review) и экспертной оценки IT-проекта № 1.\n' +
    'Дисциплина: «Вычислительные машины, сети и системы» (НИТУ МИСИС, кафедра ИКТ).\n' +
    'Преподаватель: к.т.н., с.н.с. Микитенко И. И.\n\n' +
    'Оцениваемая команда (гр. БИВТ-26-6-9):\n' +
    '• Старший группы, докладчик: Ерепов К. М.\n' +
    '• Дизайнер (виртуальная доска Miro / веб-портал): Кашин С. К.\n' +
    '• Программист (сетевое моделирование): Утяцкий В. С.\n' +
    '• Составитель теста (тестер): Якушевский И. И.\n' +
    '• Коммуникатор (регламент и рецензирование): Горбунов К. В.\n\n' +
    'Материалы проекта для ознакомления доступны по ссылкам:\n' +
    '• GitHub репозиторий: https://github.com/kukes-misis/network-ethernet-project1\n' +
    '• Интерактивная доска: https://kukes-misis.github.io/network-ethernet-project1/\n' +
    '• Полный академический отчет (29 с. ГОСТ): https://github.com/kukes-misis/network-ethernet-project1/blob/main/docs/\n\n' +
    'Пожалуйста, оцените представленный проект по 6 официальным показателям методички кафедры (шкала от 1 до 5).'
  );
  
  form.setCollectEmail(false);
  form.setAllowResponseEdits(false);
  form.setProgressBar(true);

  // --------------------------------------------------------------------------
  // РАЗДЕЛ 1: СВЕДЕНИЯ О РЕЦЕНЗЕНТЕ
  // --------------------------------------------------------------------------
  const secReviewer = form.addSectionHeaderItem();
  secReviewer.setTitle('1. Сведения о рецензенте (оценивающем студенте / эксперте)');

  const nameItem = form.addTextItem();
  nameItem.setTitle('Ваши Фамилия, Имя и Отчество:');
  nameItem.setRequired(true);

  const groupItem = form.addListItem();
  groupItem.setTitle('Ваша учебная группа / Номер вашего проекта:');
  groupItem.setChoiceValues([
    'Проект № 2 (Беспроводные сети и технологии Wi-Fi)',
    'Проект № 3 (Сетевые протоколы стека TCP/IP и маршрутизация)',
    'Проект № 4 (Сетевая безопасность, брандмауэры и VPN)',
    'Проект № 5 (Облачные технологии и виртуализация)',
    'Проект № 6 (Оптоволоконные линии и пассивные оптические сети)',
    'Преподаватель кафедры ИКТ / Комиссия',
    'Другая группа БИВТ'
  ]);
  groupItem.setRequired(true);

  // --------------------------------------------------------------------------
  // РАЗДЕЛ 2: 6 ПОКАЗАТЕЛЕЙ ОЦЕНИВАНИЯ ПРОЕКТА (МЕТОДИЧКА, С. 33)
  // --------------------------------------------------------------------------
  const secCriteria = form.addSectionHeaderItem();
  secCriteria.setTitle('2. Оценка качества выполнения проекта по 6 показателям методички (с. 33)');
  secCriteria.setHelpText('Оцените каждый аспект по шкале от 1 (Неудовлетворительно) до 5 (Отлично).');

  // Показатель 1
  const scale1 = form.addScaleItem();
  scale1.setTitle('1. Полнота отчета, спецификация оборудования и Таблица 4.2 «до/после» (сопоставление ассоциаций и стандартов IEEE 802.3)');
  scale1.setBounds(1, 5);
  scale1.setLabels('1 — Поверхностно', '5 — Строго по стандартам');
  scale1.setRequired(true);

  // Показатель 2
  const scale2 = form.addScaleItem();
  scale2.setTitle('2. Качество оформления виртуальной доски и объективный анализ цифровых инструментов (п. 8-9 методички)');
  scale2.setBounds(1, 5);
  scale2.setLabels('1 — Слабая наглядность', '5 — Наглядный интерактивный дизайн');
  scale2.setRequired(true);

  // Показатель 3
  const scale3 = form.addScaleItem();
  scale3.setTitle('3. Аналитическая модель сетевых процессов и достоверность расчетов (CSMA/CD, задержки Store-and-Forward/Cut-Through, разгрузки NIC)');
  scale3.setBounds(1, 5);
  scale3.setLabels('1 — Формально / Расхождения', '5 — Корректные согласованные расчеты');
  scale3.setRequired(true);

  // Показатель 4
  const scale4 = form.addScaleItem();
  scale4.setTitle('4. Фонд оценочных средств (банк из 15 тестовых заданий с 1 ключом и 3 дистракторами, автоматизация Google Forms)');
  scale4.setBounds(1, 5);
  scale4.setLabels('1 — Банальные вопросы', '5 — Инженерная глубина с комментариями');
  scale4.setRequired(true);

  // Показатель 5
  const scale5 = form.addScaleItem();
  scale5.setTitle('5. Организация командной работы и защита проекта (распределение ролей 5 участников, регламент доклада до 5 мин)');
  scale5.setBounds(1, 5);
  scale5.setLabels('1 — Нарушен регламент', '5 — Слаженная командная работа');
  scale5.setRequired(true);

  // Показатель 6
  const scale6 = form.addScaleItem();
  scale6.setTitle('6. Межкомандное взаимодействие (реестр 5 вопросов смежным группам с фиксацией даты/времени, ответы на замечания)');
  scale6.setBounds(1, 5);
  scale6.setLabels('1 — Взаимодействие не показано', '5 — Полный протокол рецензирования');
  scale6.setRequired(true);

  // --------------------------------------------------------------------------
  // РАЗДЕЛ 3: ИТОГОВОЕ РЕШЕНИЕ И ОТЗЫВ
  // --------------------------------------------------------------------------
  const secSummary = form.addSectionHeaderItem();
  secSummary.setTitle('3. Итоговое экспертное заключение');

  const gradeItem = form.addMultipleChoiceItem();
  gradeItem.setTitle('Какую итоговую оценку заслуживает Проект № 1 команды гр. БИВТ-26-6-9?');
  gradeItem.setChoiceValues([
    '5 (Отлично) — максимальный балл',
    '4 (Хорошо) — с незначительными замечаниями',
    '3 (Удовлетворительно) — требует доработки',
    'Отправить на доработку'
  ]);
  gradeItem.setRequired(true);

  const prosItem = form.addParagraphTextItem();
  prosItem.setTitle('Главные сильные стороны проекта:');
  prosItem.setHelpText('Например: Таблица 4.2, обоснованная модель CSMA/CD, проработка вопросов к защите...');
  prosItem.setRequired(false);

  const consItem = form.addParagraphTextItem();
  consItem.setTitle('Замечания и вопросы для защиты:');
  consItem.setHelpText('Укажите вопросы для команды на очной защите...');
  consItem.setRequired(false);

  Logger.log('----------------------------------------------------');
  Logger.log('ФОРМА УСПЕШНО СОЗДАНА!');
  Logger.log('Ссылка для редактирования: ' + form.getEditUrl());
  Logger.log('Ссылка для прохождения (публичная): ' + form.getPublishedUrl());
  Logger.log('----------------------------------------------------');
}
